/* ------------------------------------------------------------------ tasks */

function session(
  id: string,
  userId: string,
  dayOffset: number,
  startH: number,
  durMin: number,
  endReason: TimeSession["endReason"],
  endNote?: string,
): TimeSession {
  const start = new Date();
  start.setDate(start.getDate() + dayOffset);
  start.setHours(startH, 0, 0, 0);
  const end = new Date(start.getTime() + durMin * 60_000);
  return {
    id,
    userId,
    startedAt: start.toISOString(),
    endedAt: end.toISOString(),
    endReason,
    endNote,
  };
}

/** An open session that started `minsAgo` minutes back — a live running timer. */
function openSession(id: string, userId: string, minsAgo: number): TimeSession {
  return {
    id,
    userId,
    startedAt: new Date(Date.now() - minsAgo * 60_000).toISOString(),
    endedAt: null,
    endReason: null,
  };
}

