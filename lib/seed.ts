/** Timestamp helper: n days from today at hh:mm local. */
function ts(dayOffset: number, hh: number, mm = 0): string {
  const base = new Date();
  base.setDate(base.getDate() + dayOffset);
  base.setHours(hh, mm, 0, 0);
  return base.toISOString();
}

